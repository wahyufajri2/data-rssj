    public static function getMenuGroups(): array
    {
        $role = self::getUserRole();

        $menus = self::menus();

        return array_values(array_filter($menus, function ($group) use ($role) {

            // Jika tidak ada role restriction → tampilkan
            if (!isset($group['roles'])) {
                return true;
            }

            return in_array($role, $group['roles']);
        }));
    }

    private static function getUserRole(): ?Role
    {
        if (!Auth::check()) {
            return null;
        }

        return Role::fromId((int) Auth::user()->peran_id);
    }

